export const PALABRAS = [...new Set(LISTA.split(/\s+/).filter(Boolean))];

/** Mayusculas sin tildes; la Ñ cuenta como N (el modelo no la reconoce). */
export function normalizar(s: string) {
  return s.toUpperCase().normalize("NFD").replace(/\p{M}/gu, "");
}

const INDICE = PALABRAS.map((p) => ({ p, n: normalizar(p) }));

/** Hasta `n` palabras que empiezan por lo deletreado (o que son eso mismo con tilde/Ñ). */
export function sugerir(prefijo: string, n = 4) {
  const q = normalizar(prefijo.trim());
  if (!q) return [];
  const out: string[] = [];
  for (const { p, n: np } of INDICE) {
    if (np.startsWith(q) && p !== prefijo) out.push(p);
    if (out.length >= n) break;
  }
  return out;
}
